class Performers{

    private int id_performer = -1;
    private int id_type = -1;
    private string name = "";

    public int Id_performer{
	get{return id_performer;}
	set{id_performer = value;}
    }

    public int Id_type{
	get{return id_type;}
	set{id_type = value;}
    }

    public string Name{
	get{return name;}
	set{name = value;}
    }
}
